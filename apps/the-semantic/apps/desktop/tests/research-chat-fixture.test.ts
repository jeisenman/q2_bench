import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { researchChatFixture } from '../src/research-chat-fixture.js';

test('chat fixture expands inline and opens the read-only example dialog', () => {
  const dom = new JSDOM('<main></main>');
  Object.assign(globalThis, { document: dom.window.document });
  let opens = 0;
  let closes = 0;
  Object.defineProperty(dom.window.HTMLDialogElement.prototype, 'showModal', { configurable: true, value() { opens++; this.setAttribute('open', ''); } });
  Object.defineProperty(dom.window.HTMLDialogElement.prototype, 'close', { configurable: true, value() { closes++; this.removeAttribute('open'); } });
  const stage = researchChatFixture();
  dom.window.document.querySelector('main')!.append(stage);

  assert.equal(stage.tagName, 'SECTION');
  assert.equal(stage.id, 'stage-chat');
  assert.equal(stage.hidden, false);
  assert.equal(stage.querySelector('.eyebrow')?.textContent, '00 / CHAT THREAD');
  assert.equal(stage.querySelector('h2')?.textContent, 'Chat thread');
  assert.equal(stage.textContent!.match(/Illustrative fixture · Not the original research chat/g)?.length, 2);
  const conversation = stage.querySelector<HTMLElement>('.codex-thread')!;
  assert.equal(conversation.id, 'research-chat-inline');
  assert.equal(conversation.hidden, true);
  assert.equal(conversation.querySelectorAll('.codex-message').length, 6);
  const expand = stage.querySelector<HTMLButtonElement>('.research-chat-controls button')!;
  assert.equal(expand.textContent, 'Expand chat ▾');
  assert.equal(expand.getAttribute('aria-expanded'), 'false');
  expand.click();
  assert.equal(conversation.hidden, false);
  assert.equal(expand.textContent, 'Collapse chat ▴');
  assert.equal(expand.getAttribute('aria-expanded'), 'true');
  expand.click();
  assert.equal(conversation.hidden, true);
  assert.equal(expand.textContent, 'Expand chat ▾');
  assert.equal(expand.getAttribute('aria-expanded'), 'false');

  const open = stage.querySelector<HTMLAnchorElement>('.research-chat-controls a')!;
  assert.equal(open.textContent, 'Open chat thread');
  assert.equal(open.getAttribute('href'), '#research-chat-example');
  const click = new dom.window.MouseEvent('click', { bubbles: true, cancelable: true });
  open.dispatchEvent(click);
  const dialog = stage.querySelector<HTMLDialogElement>('#research-chat-example')!;
  assert.equal(click.defaultPrevented, true);
  assert.equal(opens, 1);
  assert.equal(dialog.hasAttribute('open'), true);
  assert.equal(dialog.className, 'research-chat-dialog');
  assert.equal(dialog.querySelector('h2')?.textContent, 'Chat thread');
  assert.equal(dialog.getAttribute('aria-labelledby'), 'research-chat-dialog-heading');
  assert.equal(dialog.getAttribute('aria-describedby'), 'research-chat-dialog-caption');
  assert.equal(dialog.textContent!.match(/Illustrative fixture · Not the original research chat/g)?.length, 1);
  assert.equal(dialog.querySelectorAll('.codex-message').length, 6);
  assert.deepEqual([...dialog.querySelectorAll('.codex-message-label')].map((node) => node.textContent), ['You', 'Codex', 'You', 'Codex', 'You', 'Codex']);
  assert.equal(dialog.querySelector('form, input, textarea, select'), null);
  dialog.querySelector('h2')!.dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true }));
  assert.equal(dialog.hasAttribute('open'), true);
  dialog.dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true }));
  assert.equal(closes, 1);
  assert.equal(dialog.hasAttribute('open'), false);
  dialog.showModal();
  dialog.querySelector<HTMLButtonElement>('button')!.click();
  assert.equal(closes, 2);
  assert.equal(dialog.hasAttribute('open'), false);
  dom.window.close();
});
